"""Build fixed probe sets, eval sets and training-document pools (model-agnostic text, shared by all runs).

Outputs (datasets/prepared/):
  probes.json   : {"general": [...1000 WikiText-103 test/val paragraphs], "medical": [...300], "code": [...300]}
  train_docs_<domain>.jsonl : training documents (held-out probe/eval docs excluded)
  heldout_<domain>.json     : 100 held-out documents for in-domain loss
  mmlu.json, arc_easy.json  : general-knowledge eval items (fixed random subsets)
"""
import json, os, random
import pandas as pd

HUB = "/data/transformers/hub"
OUT = "datasets/prepared"
os.makedirs(OUT, exist_ok=True)
rng = random.Random(0)

def snap(repo):
    d = f"{HUB}/datasets--{repo.replace('/', '--')}/snapshots"
    return os.path.join(d, os.listdir(d)[0])

# ---- WikiText-103: probes from test+validation, training docs (general control domain) from train
wt = snap("Salesforce/wikitext") + "/wikitext-103-raw-v1/"
def wt_paragraphs(files):
    paras = []
    for f in files:
        for t in pd.read_parquet(wt + f).text:
            t = t.strip()
            if len(t) >= 400 and not t.startswith("="):
                paras.append(t)
    return paras
gen_eval = wt_paragraphs(["test-00000-of-00001.parquet", "validation-00000-of-00001.parquet"])
rng.shuffle(gen_eval)
gen_probes, gen_heldout = gen_eval[:1000], gen_eval[1000:1100]
gen_train = wt_paragraphs(["train-00000-of-00002.parquet"])
rng.shuffle(gen_train)
gen_train = gen_train[:60000]

# ---- Medical: Asclepius synthetic clinical notes (unique notes)
med = pd.read_csv(snap("starmpcc/Asclepius-Synthetic-Clinical-Notes") + "/synthetic.csv").note.drop_duplicates().tolist()
rng.shuffle(med)
med_probes, med_heldout, med_train = med[:300], med[300:400], med[400:40400]

# ---- Code: codeparrot-clean-valid python files (moderate length, not autogenerated)
code = pd.read_parquet("datasets/code/code.parquet")
code = code[(~code.autogenerated) & (code.content.str.len().between(800, 20000))].content.tolist()
rng.shuffle(code)
code_probes, code_heldout, code_train = code[:300], code[300:400], code[400:30400]

json.dump({"general": gen_probes, "medical": med_probes, "code": code_probes}, open(f"{OUT}/probes.json", "w"))
for name, tr, ho in [("general", gen_train, gen_heldout), ("medical", med_train, med_heldout), ("code", code_train, code_heldout)]:
    with open(f"{OUT}/train_docs_{name}.jsonl", "w") as f:
        for t in tr:
            f.write(json.dumps(t) + "\n")
    json.dump(ho, open(f"{OUT}/heldout_{name}.json", "w"))
    print(name, "train docs", len(tr), "chars", sum(map(len, tr)))

# ---- MMLU: 10 questions per subject (57 subjects -> 570), fixed seed
mm = pd.read_parquet(snap("cais/mmlu") + "/all/test-00000-of-00001.parquet")
mm = mm.groupby("subject").sample(n=10, random_state=0)
mmlu = [{"q": r.question, "choices": list(r.choices), "answer": int(r.answer), "subject": r.subject} for r in mm.itertuples()]
json.dump(mmlu, open(f"{OUT}/mmlu.json", "w"))

# ---- ARC-Easy test: 500 random questions
arc = pd.read_parquet("datasets/arc/arc_easy_test.parquet").sample(500, random_state=0)
arc_items = []
for r in arc.itertuples():
    labels = list(r.choices["label"])
    arc_items.append({"q": r.question, "choices": list(r.choices["text"]), "answer": labels.index(r.answerKey)})
json.dump(arc_items, open(f"{OUT}/arc_easy.json", "w"))
print("probes", len(gen_probes), len(med_probes), len(code_probes), "mmlu", len(mmlu), "arc", len(arc_items))
